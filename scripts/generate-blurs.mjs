// One-off generator: writes 10px base64 blur placeholders for every photo.
// Rerun only when photos change:  node scripts/generate-blurs.mjs
import { createReadStream, existsSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { pipeline } from "node:stream/promises";
import sharp from "sharp";

const publicDir = path.resolve("public");
const photosDir = path.join(publicDir, "photos");
const heroSource = path.resolve("photos-original", "hero.jpg");

const files = existsSync(photosDir)
  ? (await import("node:fs")).readdirSync(photosDir).filter((f) => f.endsWith(".jpg")).sort()
  : [];

if (!existsSync(heroSource)) {
  console.error(`hero source missing: ${heroSource}`);
  process.exit(1);
}

function decode(jpegBase64) {
  const binary = Buffer.from(jpegBase64, "base64");
  return `data:image/jpeg;base64,${binary.toString("base64")}`;
}

const map = {};
const seen = new Set();

async function add(src, key) {
  const digest = createHash("sha1").update(src).digest("hex").slice(0, 12);
  if (seen.has(digest)) {
    map[key] = map[`__dup_${digest}`] ?? map[key];
    return;
  }
  seen.add(digest);
  const buffer = await sharp(src)
    .resize(10, null, { fit: "inside" })
    .jpeg({ quality: 40 })
    .toBuffer();
  const dataUri = `data:image/jpeg;base64,${buffer.toString("base64")}`;
  map[`__dup_${digest}`] = dataUri;
  map[key] = dataUri;
  console.log(`${key} <- ${path.basename(src)}`);
}

for (const file of files) {
  await add(path.join(photosDir, file), path.parse(file).name);
}

await add(heroSource, "hero");

const out = path.join("lib", "blur-placeholders.ts");
writeFileSync(
  out,
  `// Generated by scripts/generate-blurs.mjs. Do not edit by hand.\n` +
    `export const blurPlaceholders: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`
);
console.log(`wrote ${out}`);
